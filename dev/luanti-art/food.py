def grid(palette, text):
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(text.strip("\n").split("\n")):
        for x, c in enumerate(row):
            if c in palette:
                img.putpixel((x, y), hexc(palette[c]) + (255,))
    return img


# crops: stalks that grow with the stage, leaves on alternate rows, and at the last stage what grows underground
# shows at their foot
CROPS = {
    "carrots": (LEAF, {"o": "#e8761c", "O": "#a8470e"}),
    "potatoes": ({"G": "#2a5a1a", "g": "#3f8a2e", "l": "#6cba48"}, {"o": "#d4a85a", "O": "#8a6030"}),
    "beetroots": ({"G": "#5a0f2a", "g": "#4fa83a", "l": "#8ad35a"}, {"o": "#9c1f45", "O": "#5a0f2a"}),
}
HEIGHTS = [3, 6, 9, 12]
STALKS = [[5, 10], [3, 7, 12], [2, 6, 9, 13], [2, 5, 8, 11, 14]]


def crop(leaf, root, stage):
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))

    def put(x, y, c):
        if 0 <= x < 16 and 0 <= y < 16:
            img.putpixel((x, y), hexc(c) + (255,))

    h = HEIGHTS[stage]
    for i, x in enumerate(STALKS[stage]):
        top = 16 - h + (i % 2) * 2
        lean = -1 if i % 2 else 1
        for y in range(top, 16):
            put(x, y, leaf["G"])
        # a leaf every other row, out and up to one side then the other
        for n, y in enumerate(range(top + 1, 15, 2)):
            side = lean if n % 2 else -lean
            put(x + side, y, leaf["g"])
            put(x + 2 * side, y - 1, leaf["l"] if y < top + 4 else leaf["g"])
        put(x, top, leaf["l"])
        put(x + lean, top - 1, leaf["l"])
        if stage == 3 and i % 2 == 0:
            put(x, 14, root["o"])
            put(x, 15, root["o"])
            put(x + 1, 15, root["O"])
    return img


os.makedirs(OUT, exist_ok=True)
for name, (palette, text) in SPRITES.items():
    grid(palette, text).save(f"{OUT}/{name}.png")
for name, (leaf, root) in CROPS.items():
    for s in range(4):
        crop(leaf, root, s).save(f"{OUT}/goodluck_food_{name}_{s + 1}.png")
