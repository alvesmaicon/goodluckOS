def grid(palette, text):
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(text.strip("\n").split("\n")):
        for x, c in enumerate(row):
            if c in palette:
                img.putpixel((x, y), hexc(palette[c]) + (255,))
    return img


# crops: stalks that grow with the stage, leaves on alternate rows, and at the last stage what grows underground
# shows at their foot
